"""Generate docs/PARAMETERS.md: the tunable parameters in sitl/ and swarm_core/ - public UPPER_CASE numeric/tuple
constants, the fields of the parameter dataclasses (``*Params``) and numeric defaults of constructor arguments of
selected classes - with value, location and the comment next to it. NOT covered: CLI defaults, values computed by
expressions, and the profile dictionaries (``swarm_core/config.py``, ``SITL_SENSOR_PROFILE_OVERRIDES``). `python3 -m tools.parameter_table` rewrites the file; the test suite fails if
the file is out of date, so the table always matches the code."""
from __future__ import annotations

import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "PARAMETERS.md"
PACKAGES = ("sitl", "swarm_core")
CONSTRUCTOR_DEFAULTS = {"EstimateHealth", "ObstacleSensor", "AdaptiveMembership", "RunMetrics", "WindModel",
                        "DecentralizedController", "CentralizedController", "HybridController"}


def _constants(path: Path):
    src = path.read_text(encoding="utf-8")
    lines = src.splitlines()
    tree = ast.parse(src)
    scopes = [(None, tree.body)] + [(n.name, n.body) for n in tree.body if isinstance(n, ast.ClassDef)]
    for owner, body in scopes:
        for node in body:
            target = None
            if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
                target = node.targets[0].id
            elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name) and node.value is not None:
                target = node.target.id
            in_params = owner is not None and owner.endswith("Params")
            if not target or target.startswith("_") or not (target.isupper() or in_params):
                continue
            try:
                value = ast.literal_eval(node.value)
            except (ValueError, SyntaxError, TypeError):
                continue
            if not isinstance(value, (int, float, tuple)) or isinstance(value, bool):
                continue
            line = lines[node.lineno - 1]
            comment = line.split("#", 1)[1].strip() if "#" in line else ""
            yield (owner or "(module)"), target, value, node.lineno, comment
    for node in tree.body:                        # numeric defaults of constructor arguments (e.g. EstimateHealth)
        if isinstance(node, ast.ClassDef) and node.name in CONSTRUCTOR_DEFAULTS:
            init = next((f for f in node.body if isinstance(f, ast.FunctionDef) and f.name == "__init__"), None)
            if init is None:
                continue
            args = init.args.args[-len(init.args.defaults):] if init.args.defaults else []
            for arg, default in list(zip(args, init.args.defaults)) + list(zip(init.args.kwonlyargs, init.args.kw_defaults)):
                try:
                    value = ast.literal_eval(default) if default is not None else None
                except (ValueError, SyntaxError):
                    continue
                if isinstance(value, (int, float)) and not isinstance(value, bool):
                    yield f"{node.name}.__init__", arg.arg, value, init.lineno, "constructor default"


def render() -> str:
    rows = ["# Tunable parameters (generated)", "",
            "Generated by `python3 -m tools.parameter_table` from the code; do not edit by hand (a test checks it is",
            "current). **Coverage:** public UPPER_CASE literal constants, fields of the `*Params` dataclasses and numeric",
            "constructor defaults of selected classes. **Not covered:** CLI defaults, values computed by expressions, and",
            "the profile dictionaries (`swarm_core/config.py`, `SITL_SENSOR_PROFILE_OVERRIDES`). Values are code defaults;",
            "several are scaled at run time (`--time-scale`, `--position-sigma`, `--formation-scale`, `--realistic`).", ""]
    for package in PACKAGES:
        for path in sorted((ROOT / package).rglob("*.py")):
            found = list(_constants(path))
            if not found:
                continue
            rows += [f"## `{path.relative_to(ROOT)}`", "", "| Name | Value | Where | Note |", "|---|---|---|---|"]
            for owner, name, value, lineno, comment in found:
                text = repr(value)
                if len(text) > 60:
                    text = text[:57] + "..."
                rows.append(f"| `{name}` | `{text}` | {owner}, line {lineno} | {comment.replace('|', '/')} |")
            rows.append("")
    return "\n".join(rows) + "\n"


def main() -> None:
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
